"""Vendored sky catalog (data/reference/sky) loading and name search.

The catalog is generated by scripts/build_sky_catalog.py from pinned upstream
data; this module only reads it. Search is a case- and accent-insensitive
substring match over designations, long designations, names and aliases, ranked
exact > prefix > substring, then by the field that matched, then by brightness.
"""

from __future__ import annotations

import json
import math
import re
import unicodedata
from collections.abc import Iterable
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

CATALOG_FILE = "sky_catalog.v1.json"
DEEP_STARS_FILE = "sky_stars_deep.v1.json"
CATALOG_SCHEMA = "skywatcher.sky-catalog/v1"

_FIELD_PRIORITY = {"designation": 0, "long_designation": 1, "name": 2, "alias": 3}
_HIP_QUERY = re.compile(r"^hip\s*(\d+)$")


def normalize_text(text: str) -> str:
    """Case- and accent-insensitive comparison key ("Boötes" -> "bootes")."""
    decomposed = unicodedata.normalize("NFKD", text)
    stripped = "".join(ch for ch in decomposed if not unicodedata.combining(ch))
    return " ".join(stripped.casefold().split())


@dataclass(frozen=True)
class CatalogObject:
    """A searchable fixed target: a named star or a Messier/Caldwell object."""

    id: str
    kind: str  # star | messier | caldwell
    designation: str
    long_designation: str
    name: str | None
    aliases: tuple[str, ...]
    object_type: str
    constellation: str | None
    magnitude: float | None
    size_arcmin: tuple[float, float] | None
    ra_deg: float
    dec_deg: float

    @property
    def display(self) -> str:
        if self.name and self.name != self.designation:
            return f"{self.designation} ({self.name})"
        return self.designation

    def search_fields(self) -> Iterable[tuple[str, str]]:
        yield "designation", self.designation
        yield "long_designation", self.long_designation
        if self.name:
            yield "name", self.name
        for alias in self.aliases:
            yield "alias", alias


@dataclass(frozen=True)
class SearchMatch:
    """How a search query matched an object (rank 0 exact, 1 prefix, 2 substring)."""

    rank: int
    field: str
    text: str


@dataclass(frozen=True)
class SkyCatalog:
    """The loaded catalog plus precomputed unit vectors for fast chart filtering."""

    schema_version: str
    data_license: str
    objects: tuple[CatalogObject, ...]
    by_id: dict[str, CatalogObject]
    stars: tuple[tuple[int, float, float, float], ...]  # (hip, ra, dec, mag)
    star_vectors: tuple[tuple[float, float, float], ...]
    star_labels: dict[int, str]
    deep_stars: tuple[tuple[float, float, float], ...]  # (ra, dec, mag)
    deep_star_vectors: tuple[tuple[float, float, float], ...]
    constellations: tuple[dict, ...]
    constellation_lines: tuple[dict, ...]

    def get(self, target_id: str) -> CatalogObject | None:
        if target_id in self.by_id:
            return self.by_id[target_id]
        match = re.fullmatch(r"star:hip:(\d+)", target_id)
        if match:
            return self._unnamed_star(int(match.group(1)))
        return None

    def _unnamed_star(self, hip: int) -> CatalogObject | None:
        for star_hip, ra, dec, mag in self.stars:
            if star_hip == hip:
                return CatalogObject(
                    id=f"star:hip:{hip}",
                    kind="star",
                    designation=f"HIP {hip}",
                    long_designation=f"HIP {hip}",
                    name=None,
                    aliases=(),
                    object_type="star",
                    constellation=None,
                    magnitude=mag,
                    size_arcmin=None,
                    ra_deg=ra,
                    dec_deg=dec,
                )
        return None


def unit_vector(ra_deg: float, dec_deg: float) -> tuple[float, float, float]:
    """J2000 RA/Dec (degrees) -> unit vector."""
    ra, dec = math.radians(ra_deg), math.radians(dec_deg)
    return math.cos(dec) * math.cos(ra), math.cos(dec) * math.sin(ra), math.sin(dec)


@lru_cache(maxsize=4)
def load_catalog(directory: Path) -> SkyCatalog:
    """Load and index the vendored catalog in ``directory`` (cached per path)."""
    raw = json.loads((directory / CATALOG_FILE).read_text(encoding="utf-8"))
    if raw.get("schema_version") != CATALOG_SCHEMA:
        raise ValueError(f"unsupported sky catalog schema {raw.get('schema_version')!r}")
    deep = json.loads((directory / DEEP_STARS_FILE).read_text(encoding="utf-8"))

    objects: list[CatalogObject] = []
    star_labels: dict[int, str] = {}
    stars = tuple((int(h), float(r), float(d), float(m)) for h, r, d, m in raw["stars"])
    star_by_hip = {star[0]: star for star in stars}
    for hip_text, entry in raw["star_names"].items():
        hip = int(hip_text)
        _, ra, dec, mag = star_by_hip[hip]
        star_labels[hip] = entry["label"]
        objects.append(
            CatalogObject(
                id=f"star:hip:{hip}",
                kind="star",
                designation=entry["label"],
                long_designation=entry["label"],
                name=entry.get("name"),
                aliases=tuple(entry.get("aliases", ())),
                object_type="star",
                constellation=entry.get("constellation"),
                magnitude=mag,
                size_arcmin=None,
                ra_deg=ra,
                dec_deg=dec,
            )
        )
    for item in raw["deep_sky"]:
        size = item.get("size_arcmin")
        objects.append(
            CatalogObject(
                id=item["id"],
                kind=item["catalog"],
                designation=item["designation"],
                long_designation=item["long_designation"],
                name=item.get("name"),
                aliases=tuple(item.get("aliases", ())),
                object_type=item["object_type"],
                constellation=item.get("constellation"),
                magnitude=item.get("magnitude"),
                size_arcmin=(float(size[0]), float(size[1])) if size else None,
                ra_deg=float(item["ra_deg"]),
                dec_deg=float(item["dec_deg"]),
            )
        )
    deep_stars = tuple((float(r), float(d), float(m)) for r, d, m in deep["stars"])
    return SkyCatalog(
        schema_version=raw["schema_version"],
        data_license=raw.get("data_license", ""),
        objects=tuple(objects),
        by_id={item.id: item for item in objects},
        stars=stars,
        star_vectors=tuple(unit_vector(ra, dec) for _, ra, dec, _ in stars),
        star_labels=star_labels,
        deep_stars=deep_stars,
        deep_star_vectors=tuple(unit_vector(ra, dec) for ra, dec, _ in deep_stars),
        constellations=tuple(raw["constellations"]),
        constellation_lines=tuple(raw["constellation_lines"]),
    )


def match_query(query: str, fields: Iterable[tuple[str, str]]) -> SearchMatch | None:
    """Best match of a normalized query against (field, text) pairs, or None."""
    best: tuple[int, int, str, str] | None = None
    for field, text in fields:
        key = normalize_text(text)
        if not key:
            continue
        if key == query:
            rank = 0
        elif key.startswith(query):
            rank = 1
        elif query in key:
            rank = 2
        else:
            continue
        candidate = (rank, _FIELD_PRIORITY.get(field, 3), field, text)
        if best is None or candidate[:2] < best[:2]:
            best = candidate
    if best is None:
        return None
    return SearchMatch(rank=best[0], field=best[2], text=best[3])


def search_catalog(
    catalog: SkyCatalog, query: str, kinds: frozenset[str]
) -> list[tuple[CatalogObject, SearchMatch]]:
    """Catalog objects of ``kinds`` matching ``query``, best first."""
    normalized = normalize_text(query)
    if not normalized:
        return []
    results: list[tuple[CatalogObject, SearchMatch]] = []
    hip = _HIP_QUERY.match(normalized)
    if hip and "star" in kinds:
        star = catalog.get(f"star:hip:{int(hip.group(1))}")
        if star is not None:
            results.append((star, SearchMatch(0, "alias", f"HIP {int(hip.group(1))}")))
    seen = {item.id for item, _ in results}
    for item in catalog.objects:
        if item.kind not in kinds or item.id in seen:
            continue
        match = match_query(normalized, item.search_fields())
        if match is not None:
            results.append((item, match))
    results.sort(key=lambda pair: search_sort_key(pair[1], pair[0].magnitude, pair[0].display))
    return results


def search_sort_key(match: SearchMatch, magnitude: float | None, display: str) -> tuple:
    """Shared ordering for catalog, solar-system and satellite search results."""
    return (
        match.rank,
        _FIELD_PRIORITY.get(match.field, 3),
        magnitude if magnitude is not None else math.inf,
        display.casefold(),
    )
